-- 1) جدول العروض
create table if not exists public.site_quotes (
  id             bigint generated by default as identity primary key,
  number         text not null unique,
  lang           text not null default 'ar' check (lang in ('ar','he')),
  customer_name  text not null default '',
  customer_phone text not null default '',
  event_date     date,
  guests         text,
  valid_days     int  not null default 7,
  items          jsonb not null default '[]'::jsonb,
  subtotal       numeric(10,2) not null default 0,
  special_total  numeric(10,2),
  total          numeric(10,2) not null default 0,
  notes          text not null default '',
  status         text not null default 'draft' check (status in ('draft','sent','accepted','rejected')),
  pdf_path       text,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
alter table public.site_quotes enable row level security;
drop policy if exists "site_quotes admin" on public.site_quotes;
create policy "site_quotes admin" on public.site_quotes for all to authenticated
  using (public.is_site_admin()) with check (public.is_site_admin());
grant select, insert, update, delete on public.site_quotes to authenticated;

-- 2) ترقيم تلقائي: TP-26-0001 (الرقم بيكمل بدون ما يرجع لورا)
create sequence if not exists public.site_quote_seq start 1;
create or replace function public.next_quote_number()
returns text language plpgsql security definer set search_path = public
as $$
begin
  if not public.is_site_admin() then raise exception 'not allowed'; end if;
  return 'TP-' || to_char(now() at time zone 'Asia/Jerusalem','YY') || '-' || lpad(nextval('public.site_quote_seq')::text, 4, '0');
end $$;
revoke all on function public.next_quote_number() from public, anon;
grant execute on function public.next_quote_number() to authenticated;

-- 3) مخزن ملفات الـ PDF: الرابط بيفتح للزبون (اسم الملف فيه رقم عشوائي)، الرفع للأدمن بس — حد 10MB
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('quotes', 'quotes', true, 10485760, array['application/pdf'])
on conflict (id) do update set public = true, file_size_limit = 10485760, allowed_mime_types = array['application/pdf'];

drop policy if exists "quotes admin insert" on storage.objects;
drop policy if exists "quotes admin update" on storage.objects;
drop policy if exists "quotes admin delete" on storage.objects;
drop policy if exists "quotes admin select" on storage.objects;
create policy "quotes admin insert" on storage.objects for insert to authenticated with check (bucket_id = 'quotes' and public.is_site_admin());
create policy "quotes admin update" on storage.objects for update to authenticated using (bucket_id = 'quotes' and public.is_site_admin());
create policy "quotes admin delete" on storage.objects for delete to authenticated using (bucket_id = 'quotes' and public.is_site_admin());
create policy "quotes admin select" on storage.objects for select to authenticated using (bucket_id = 'quotes' and public.is_site_admin());

